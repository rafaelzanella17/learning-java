public class Logicos {

    public static void main(String[] args) {

        // ------------------------------
        // OPERADORES LÓGICOS
        // ------------------------------

        boolean x = true;
        boolean y = false;

        System.out.println(x && y); // AND lógico
        System.out.println(x || y); // OR lógico
        System.out.println(!x);     // NOT lógico
    }
}
